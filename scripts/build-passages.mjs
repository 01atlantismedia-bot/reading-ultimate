// Generates worker/src/passages.generated.js from every JSON file in worker/passages/.
// Passages are bundled INTO the Worker, so they are never publicly reachable as static files.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'worker');
const files = readdirSync(join(root, 'passages')).filter(f => f.endsWith('.json')).sort();
const problems = [];
// Difficult-word lists (English + Russian) live in worker/glossaries.json and are merged into the passages here.
const glossPath = join(root, 'glossaries.json');
const GLOSS = existsSync(glossPath) ? JSON.parse(readFileSync(glossPath, 'utf8')) : {};
const passages = {};

for (const f of files) {
  const p = JSON.parse(readFileSync(join(root, 'passages', f), 'utf8'));
  const sids = new Set(p.paragraphs.flatMap(pa => pa.sentences.map(s => s.id)));
  const seen = new Set();
  // Full-test imports (format "test") come with answer keys and anchors but no hand-written explanations,
  // and a few matching questions have no single evidence sentence. Those are allowed; hand-made passages must be complete.
  const isTest = p.format === 'test';
  for (const g of p.groups) for (const q of g.questions) {
    if (seen.has(q.id)) problems.push(`${f}: duplicate question id ${q.id}`);
    seen.add(q.id);
    if (q.evidence ? !sids.has(q.evidence) : !isTest) problems.push(`${f}: ${q.id} evidence "${q.evidence}" is not a sentence id`);
    if (q.options) {
      const keys = q.options.map(o => (g.type === 'mcq' || g.type === 'multi' ? o[0] : o));
      const want = Array.isArray(q.answer) ? q.answer : [q.answer];
      if (!want.every(a => keys.includes(a))) problems.push(`${f}: ${q.id} answer "${q.answer}" not among options`);
    }
    if (!isTest && (!q.explanation?.en || !q.explanation?.ru)) problems.push(`${f}: ${q.id} missing EN/RU explanation`);
  }
  if (f.replace('.json', '') !== p.id) problems.push(`${f}: id "${p.id}" does not match filename`);
  if (GLOSS[p.id]) p.glossary = GLOSS[p.id];
  const text = p.paragraphs.flatMap(pa => pa.sentences.map(s => s.text)).join(' ');
  for (const w of p.glossary || []) {
    if (!w.word || !w.def_en || !w.ru) problems.push(`${f}: glossary entry "${w.word}" needs word, def_en and ru`);
    else if (!new RegExp('\\b' + w.word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?:s|es|ed|ing)?\\b', 'i').test(text)) problems.push(`${f}: glossary word "${w.word}" is not in the passage text`);
  }
  passages[p.id] = p;
}
if (problems.length) { console.error('Passage problems:\n- ' + problems.join('\n- ')); process.exit(1); }

writeFileSync(join(root, 'src', 'passages.generated.js'), '// AUTO-GENERATED by scripts/build-passages.mjs — do not edit\nexport const PASSAGES = ' + JSON.stringify(passages) + ';\n');
console.log(`Bundled ${files.length} passage(s) with ${Object.values(passages).reduce((n, p) => n + (p.glossary || []).length, 0)} glossary words, all checks passed.`);
